"""Run every benchmark and write experiments/RESULTS.md.

    docker compose run --rm tests python -m experiments.run_all
"""

import asyncio
from pathlib import Path

from experiments import claim_throughput, duplicate_effects, recovery_time, replay_time, resume_vs_restart
from experiments.common import environment


async def main() -> None:
    sections = [f"# Benchmark results\n\nGenerated by `python -m experiments.run_all` on {await environment()}."]
    for module in (replay_time, claim_throughput, resume_vs_restart, recovery_time):
        print(f"running {module.__name__} ...", flush=True)
        sections.append(await module.main())
    print("running experiments.duplicate_effects ...", flush=True)
    sections.append(duplicate_effects.main())
    report = "\n\n".join(sections) + "\n"
    Path(__file__).with_name("RESULTS.md").write_text(report)
    print(report)


if __name__ == "__main__":
    asyncio.run(main())
